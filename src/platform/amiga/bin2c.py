# Embeds a binary file (the font/icon PNG assets) as a C byte array at
# build time, so the Amiga frontend ships as a single self-contained
# executable with no loose asset files to install/lose -- the same
# problem other platforms solve with devkitPro's raw2c or an
# objcopy-as-binary trick, neither of which is reliably available for
# this cross toolchain.
import sys


def main():
    if len(sys.argv) != 4:
        sys.stderr.write("usage: bin2c.py INPUT SYMBOL OUTPUT.c\n")
        return 1

    in_path, symbol, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(in_path, "rb") as f:
        data = f.read()

    with open(out_path, "w") as f:
        f.write("/* Generated by bin2c.py from %s -- do not edit. */\n" % in_path)
        f.write("#include <stddef.h>\n\n")
        f.write("const unsigned char %s[] = {\n" % symbol)
        for i in range(0, len(data), 16):
            f.write("\t" + ",".join(str(b) for b in data[i:i + 16]) + ",\n")
        f.write("};\n")
        f.write("const size_t %s_size = sizeof(%s);\n" % (symbol, symbol))

    return 0


if __name__ == "__main__":
    sys.exit(main())
